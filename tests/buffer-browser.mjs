import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { createServer } from '../server.mjs';

const directory = process.env.CODA_MUSIC_DIR;
if (!directory) throw new Error('Set CODA_MUSIC_DIR to the prepared fixture cache');
const releases = new Map();
const server = createServer({ musicDirectory: directory, liveMusic: async id => {
  const bytes = await readFile(join(directory, `${id}.webm`));
  return { bytes: bytes.length, stream: new ReadableStream({ start(controller) {
    controller.enqueue(bytes.subarray(0, 512 * 1024));
    releases.set(id, () => { controller.enqueue(bytes.subarray(512 * 1024)); controller.close(); });
  } }) };
} });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.locator('#live').click();
  await page.waitForFunction(() => document.querySelector('#delivery-status').textContent.includes('Ready: live music'));
  assert.equal((await (await fetch(base + '/api/live/status')).json()).tracks.length, 0);
  await page.locator('#buffer-next').check({ timeout: 2000 });
  await page.locator('#play').click();
  await page.waitForFunction(() => document.querySelector('audio').currentTime > 0.25);
  let status = await (await fetch(base + '/api/live/status')).json();
  assert.equal(status.tracks[0].completedAt, null, 'First song still starts progressively');
  assert.equal(await page.locator('audio').getAttribute('src'), '/live/4D7u5KF7SP8.webm');
  await page.waitForFunction(() => document.querySelector('#buffer-status').textContent.includes('Buffering next song'));
  status = await (await fetch(base + '/api/live/status')).json();
  assert.deepEqual(status.tracks.map(track => track.id), ['4D7u5KF7SP8', 't0AvpJ74sBc']);
  assert.equal(status.tracks[1].completedAt, null, 'Next song is not marked ready before EOF');
  releases.get('4D7u5KF7SP8')(); releases.get('t0AvpJ74sBc')();
  await page.waitForFunction(() => document.querySelector('#buffer-status').textContent.includes('Next song ready on this device'));
  await page.screenshot({ path: 'artifacts/buffer-390.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.setViewportSize({ width: 728, height: 900 });
  await page.screenshot({ path: 'artifacts/buffer-728.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('audio').evaluate(audio => { audio.pause(); audio.currentTime = audio.duration - 0.5; });
  await page.waitForFunction(() => !document.querySelector('audio').seeking && document.querySelector('audio').readyState >= 3);
  await page.context().setOffline(true);
  await page.locator('#play').click();
  await page.waitForFunction(() => document.querySelector('#now').textContent === '三年二班');
  await page.waitForFunction(() => document.querySelector('audio').currentTime > 0.25 && !document.querySelector('audio').paused);
  assert.ok((await page.locator('audio').getAttribute('src')).startsWith('blob:'), 'Next song plays a browser Blob while networking is disabled');
  await page.locator('audio').evaluate(audio => { audio.currentTime = 150; });
  await page.waitForFunction(() => document.querySelector('audio').currentTime > 150.25);
  await page.waitForFunction(() => document.querySelector('#buffer-status').textContent.includes('Buffer unavailable'));
  await page.evaluate(() => { for (let i = 0; i < 301; i++) document.dispatchEvent(new Event('resume')); });
  const download = page.waitForEvent('download'); await page.locator('#export').click();
  await (await download).saveAs('artifacts/buffer-export.json');
  const result = JSON.parse(await readFile('artifacts/buffer-export.json', 'utf8'));
  assert.equal(result.audioDelivery, 'live');
  assert.equal(result.eventsTruncated, true);
  assert.equal(result.liveBrowserBuffering.enabled, true);
  assert.equal(result.liveBrowserBuffering.playback.storage, 'phone-buffer');
  assert.equal(result.liveBrowserBuffering.playback.trackId, 't0AvpJ74sBc');
  assert.equal(result.liveBrowserBuffering.tracks.find(track => track.id === 't0AvpJ74sBc').bytes, 4864721);
  assert.equal(result.liveBrowserBuffering.tracks.find(track => track.id === 'dsUTcSVdU2U').status, 'failed');
  assert.ok(result.liveBrowserBuffering.tracks.length <= 2);
  assert.ok(result.checks.every(check => check.status === 'NOT RUN'));

  const edited = await browser.newPage();
  edited.on('pageerror', error => errors.push(error.message));
  await edited.addInitScript(() => {
    window.audioUrls = new Set(); window.revokedAudioUrls = [];
    const create = URL.createObjectURL.bind(URL), revoke = URL.revokeObjectURL.bind(URL);
    URL.createObjectURL = blob => { const url = create(blob); if (blob.type.startsWith('audio/')) window.audioUrls.add(url); return url; };
    URL.revokeObjectURL = url => { if (window.audioUrls.delete(url)) window.revokedAudioUrls.push(url); revoke(url); };
  });
  await edited.goto(base); await edited.locator('#live').click();
  await edited.locator('#buffer-next').check(); await edited.locator('#play').click();
  await edited.waitForFunction(() => document.querySelector('#buffer-status').textContent.includes('Next song ready on this device'));
  await edited.locator('#queue li').nth(1).getByRole('button', { name: 'Move down', exact: true }).click();
  await edited.waitForFunction(() => document.querySelector('#buffer-status').textContent.includes('Buffering next song: 半島鐵盒'));
  await edited.waitForFunction(async () => (await (await fetch('/api/live/status')).json()).tracks.some(track => track.id === 'dsUTcSVdU2U' && track.receivedBytes > 0));
  await edited.locator('#queue li').nth(1).getByRole('button', { name: 'Remove', exact: true }).click();
  releases.get('dsUTcSVdU2U')();
  await edited.waitForFunction(() => document.querySelector('#buffer-status').textContent.includes('Next song ready on this device: 三年二班'));
  assert.equal(await edited.evaluate(() => window.revokedAudioUrls.length), 1, 'Reorder releases the obsolete ready Blob');
  assert.equal(await edited.evaluate(() => window.audioUrls.size), 1, 'A removed pending download never creates a stale Blob');
  await edited.locator('#next').click();
  await edited.waitForFunction(() => document.querySelector('audio').currentTime > 0.2 && document.querySelector('audio').src.startsWith('blob:'));
  await edited.waitForFunction(() => document.querySelector('#buffer-status').textContent.includes('Next song ready on this device'));
  assert.equal(await edited.evaluate(() => window.audioUrls.size), 2, 'Only current and next Blobs are retained');
  await edited.locator('#reset').click();
  assert.equal(await edited.evaluate(() => window.audioUrls.size), 0, 'Reset revokes all ready Blobs');
  assert.equal(await edited.locator('audio').getAttribute('src'), null);

  await edited.locator('#play').click();
  await edited.waitForFunction(() => document.querySelector('#buffer-status').textContent.includes('Next song ready on this device: 三年二班'));
  let lookaheadRequests = 0;
  edited.on('request', request => { if (request.resourceType() === 'fetch' && new URL(request.url()).pathname.startsWith('/live/')) lookaheadRequests++; });
  await edited.locator('audio').evaluate(audio => {
    audio.play = () => new Promise((resolve, reject) => { window.rejectPlay = () => reject(new DOMException('Blocked by test', 'NotAllowedError')); });
  });
  await edited.locator('#queue li').nth(2).getByRole('button', { name: 'Play', exact: true }).click();
  assert.equal(await edited.evaluate(() => window.audioUrls.size), 0, 'Selecting C releases obsolete B even while play is pending');
  assert.equal(await edited.locator('#buffer-status').textContent().then(text => text.includes('Next song ready')), false, 'A pending selection never advertises stale readiness');
  assert.equal(lookaheadRequests, 0, 'A pending selection does not initiate new lookahead');
  await edited.evaluate(() => window.rejectPlay());
  await edited.waitForFunction(() => document.querySelector('#now').textContent.includes('Playback failed'));
  assert.equal(await edited.locator('#buffer-status').textContent().then(text => text.includes('Next song ready')), false, 'Rejection leaves readiness accurate');
  await edited.close();

  const failed = await browser.newPage();
  failed.on('pageerror', error => errors.push(error.message));
  await failed.route('**/live/t0AvpJ74sBc.webm', route => route.request().resourceType() === 'fetch'
    ? route.fulfill({ status: 200, contentType: 'audio/webm', body: 'incomplete' }) : route.continue());
  await failed.goto(base); await failed.locator('#live').click();
  await failed.locator('#buffer-next').check(); await failed.locator('#play').click();
  await failed.waitForFunction(() => document.querySelector('#buffer-status').textContent.includes('Buffer unavailable'));
  await failed.locator('#next').click();
  await failed.waitForFunction(() => document.querySelector('#now').textContent === '三年二班' && document.querySelector('audio').currentTime > 0.2);
  assert.equal(await failed.locator('audio').getAttribute('src'), '/live/t0AvpJ74sBc.webm', 'Invalid buffered bytes are never used; normal live playback remains available');
  await failed.close();
  assert.deepEqual(errors, []);
  await writeFile('artifacts/buffer-browser-check.json', JSON.stringify({ date: new Date().toISOString(), browser: browser.version(), status: 'PASS', source: 'gated prepared files through live HTTP fixtures; not fresh YouTube', firstPlaybackBeforeEOF: true, nextSongBeforeEOF: 'pending, not ready', nextTransitionAndSeekWithoutNetworking: 'PASS', failedFurtherBufferPreservesCurrentPlayback: 'PASS', persistentExportAfterTruncation: 'PASS', reorderRemovalCancellationAndResetCleanup: 'PASS', pendingAndRejectedSelectionCleanup: 'PASS', invalidBytesFallback: 'PASS', phoneBatterySaver: 'NOT RUN' }, null, 2));
  console.log('PASS: progressive first song, complete next-song Blob, offline transition/seek, bounded state, persistent export, reorder/remove/reset cleanup and invalid-byte fallback. Physical phone/Battery Saver NOT RUN.');
} finally { await browser.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
